"""python3 export_js.py <anim dir> <chars dir> <src/animart.js>
Sheets from animals/gen.py and chars/build.py as data URIs for the home (ANIMSRC, ANIMMETA).
'dog' replaces pixart.js's dog sheet (same 128 px layout)."""
import sys, json, base64, os, glob
d, cd, out = sys.argv[1], sys.argv[2], sys.argv[3]
b64 = lambda p: 'data:image/png;base64,' + base64.b64encode(open(p, 'rb').read()).decode()
man = json.load(open(os.path.join(d, 'manifest.json')))
man['chars'] = json.load(open(os.path.join(cd, 'chars.json')))
src = {'an-' + os.path.basename(p)[:-4]: b64(p) for p in sorted(glob.glob(os.path.join(d, '*.png')))}
for k in ('pierre', 'grandma'):
    src['an-' + k] = b64(os.path.join(cd, k + '.png'))
src['dog'] = b64(os.path.join(cd, 'dog.png'))
open(out, 'w').write("// generated by pixel-src/animals/export_js.py from Puti's hens, birds, fish, dog, Pierre and Grandma. Do not edit by hand.\nvar ANIMSRC=" + json.dumps(src) + ';\nvar ANIMMETA=' + json.dumps(man) + ';\n')
print(out, os.path.getsize(out))
