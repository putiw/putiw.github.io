"""python3 export_js.py <anim dir> <src/animart.js>: sheets from gen.py as data URIs for the home (ANIMSRC, ANIMMETA)."""
import sys, json, base64, os, glob
d, out = sys.argv[1], sys.argv[2]
man = json.load(open(os.path.join(d, 'manifest.json')))
src = {'an-' + os.path.basename(p)[:-4]: 'data:image/png;base64,' + base64.b64encode(open(p, 'rb').read()).decode() for p in sorted(glob.glob(os.path.join(d, '*.png')))}
open(out, 'w').write('// generated by pixel-src/animals/export_js.py from Puti\'s hens, birds and fish. Do not edit by hand.\nvar ANIMSRC=' + json.dumps(src) + ';\nvar ANIMMETA=' + json.dumps(man) + ';\n')
print(out, os.path.getsize(out))
